@router.post("/run")
async def run_forecast_pipeline(db: AsyncSession = Depends(get_db)):
    """
    Triggers live ML demand surge scan across the DC network.
    """
    surges = await DemandSensingEngine.scan_and_record_demand_surges(db)
    await db.commit()
    return {
        "success": True,
        "surges_detected": len(surges),
        "message": f"ML Demand Sensing pipeline executed. Identified {len(surges)} forward demand surges."
    }
