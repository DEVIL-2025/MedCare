router = APIRouter(prefix="/api/forecasts", tags=["Forecasts"])


@router.get("")
async def get_forecast(
    sku: Optional[str] = "P-1042",
    warehouse: Optional[str] = "BLR-01",
    horizon: Optional[str] = "30 Days",
    granularity: Optional[str] = "Daily",
    db: AsyncSession = Depends(get_db)
) -> Dict[str, Any]:
    """
    Returns ML demand forecast series generated by the trained RandomForestRegressor model.
    """
    days = 90 if "90" in (horizon or "") else (7 if "7" in (horizon or "") else 30)
    data = await PredictionService.predict_demand(db, sku or "P-1042", warehouse or "BLR-01", days)
    return data


@router.post("/train")
async def train_model(
    current_user: User = Depends(require_permission("forecast.train")),
    db: AsyncSession = Depends(get_db)
):
    """
    Triggers explicit model retraining on the current PostgreSQL/SQLite database records (Admin Only).
    """
    metadata = await ModelRegistry.retrain_model(db)
    return {
        "success": True,
        "message": "Random Forest ML model successfully retrained on database demand history.",
        "model_info": metadata
    }


@router.get("/model-info")
async def get_model_info(db: AsyncSession = Depends(get_db)):
    """
    Returns complete transparency metadata for the active ML model.
    """
    return await ModelRegistry.get_model_info(db)


